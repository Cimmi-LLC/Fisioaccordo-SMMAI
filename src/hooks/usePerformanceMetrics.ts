import { useEffect, useState } from 'react';
import { supabase } from '@/integrations/supabase/client';
import { inWindow, shiftDays, toIncrements, type PeriodWindow } from '@/lib/performance/periodo';

export type Channel = 'instagram' | 'tiktok' | 'youtube';

export interface MetricRow {
  snapshot_date: string;
  reach: number | null;
  impressions: number | null;
  engagement: number | null;
  likes: number | null;
  comments: number | null;
  saves: number | null;
  shares: number | null;
  video_views: number | null;
  video_completion_rate: number | null;
  avg_view_sec: number | null;
  watch_minutes: number | null;
  followers_total: number | null;
  new_followers: number | null;
  caption_excerpt: string | null;
  external_post_id: string;
  is_account_level: boolean;
}

export interface PerformanceQuery {
  /** Set ONE of brandId or trackedHandleId — never both. */
  brandId?: string | null;
  trackedHandleId?: string | null;
  channel: Channel;
  window: PeriodWindow;
}

export interface PerformanceResult {
  rows: MetricRow[];
  prevRows: MetricRow[];
  loading: boolean;
  error: string | null;
}

// Giorni letti prima del periodo precedente: servono il giro di ogni post
// che precede il periodo, per trasformare i totali di Instagram in aumenti.
const LOOKBACK_DAYS = 60;
const PAGE = 1000; // tetto di righe per richiesta di PostgREST

/**
 * Righe del periodo scelto e del periodo precedente di uguale durata (per i
 * delta %). I valori dei post sono sempre aumenti nel giorno, su ogni canale.
 * RLS handles authorization: admins get cross-brand reads automatically.
 */
export const usePerformanceMetrics = ({ brandId, trackedHandleId, channel, window: w }: PerformanceQuery): PerformanceResult => {
  const [state, setState] = useState<PerformanceResult>({
    rows: [], prevRows: [], loading: false, error: null,
  });
  const { from, to, prevFrom, prevTo } = w;

  useEffect(() => {
    if (!brandId && !trackedHandleId) {
      setState({ rows: [], prevRows: [], loading: false, error: null });
      return;
    }
    let cancelled = false;
    setState((s) => ({ ...s, loading: true, error: null }));

    const filterKey = brandId ? 'brand_id' : 'tracked_handle_id';
    const filterVal = (brandId || trackedHandleId)!;
    const fetchFrom = channel === 'instagram' ? shiftDays(prevFrom, -LOOKBACK_DAYS) : prevFrom;

    (async () => {
      try {
        const all: MetricRow[] = [];
        for (let offset = 0; ; offset += PAGE) {
          // cast to any: types.ts autogenerated doesn't yet include post_metrics
          const res: any = await (supabase as any)
            .from('post_metrics')
            .select('*')
            .eq(filterKey, filterVal)
            .eq('channel', channel)
            .gte('snapshot_date', fetchFrom)
            .lte('snapshot_date', to)
            .order('snapshot_date', { ascending: true })
            .order('id', { ascending: true })
            .range(offset, offset + PAGE - 1);
          if (res.error) throw new Error(res.error.message);
          const page = (res.data || []) as MetricRow[];
          all.push(...page);
          if (page.length < PAGE || cancelled) break;
        }
        if (cancelled) return;
        const rows = channel === 'instagram' ? toIncrements(all) : all;
        setState({
          rows: inWindow(rows, from, to),
          prevRows: inWindow(rows, prevFrom, prevTo),
          loading: false,
          error: null,
        });
      } catch (e) {
        if (cancelled) return;
        setState({ rows: [], prevRows: [], loading: false, error: e instanceof Error ? e.message : String(e) });
      }
    })();

    return () => { cancelled = true; };
  }, [brandId, trackedHandleId, channel, from, to, prevFrom, prevTo]);

  return state;
};
